// AdminMembershipChannels exposes eligible model names without returning provider credentials.
func AdminMembershipChannels(c *gin.Context) {
	var channels []model.Channel
	if err := model.DB.Select("id", "name", "type", "status", "models", "model_mapping", "setting").Where("status = ? AND type IN ?", common.ChannelStatusEnabled, []int{constant.ChannelTypeOpenAI, constant.ChannelTypeAzure, constant.ChannelTypeSora, constant.ChannelTypeXai, constant.ChannelTypeAnthropic, constant.ChannelTypeGemini, constant.ChannelTypeVolcEngine}).Order("id asc").Find(&channels).Error; err != nil {
		common.ApiError(c, err)
		return
	}
	type option struct {
		Profile string   `json:"profile"`
		Unit    string   `json:"unit"`
		Id      int      `json:"id"`
		Name    string   `json:"name"`
		Models  []string `json:"models"`
	}
	options := make([]option, 0)
	for _, channel := range channels {
		if channel.GetSetting().PassThroughBodyEnabled {
			continue
		}
		models := make([]string, 0)
		imageModels := make([]string, 0)
		videoModels := make([]string, 0)
		transcriptionModels := make([]string, 0)
		speechModels := make([]string, 0)
		realtimeModels := make([]string, 0)
		claudeModels := make([]string, 0)
		geminiModels := make([]string, 0)
		var mapping map[string]string
		if channel.ModelMapping != nil && *channel.ModelMapping != "" {
			if common.UnmarshalJsonStr(*channel.ModelMapping, &mapping) != nil {
				continue
			}
		}
		for _, name := range channel.GetModels() {
			upstream := name
			if mapped := mapping[name]; mapped != "" {
				upstream = mapped
			}
			if channel.Type == constant.ChannelTypeGemini && upstream == "gemini-3.8-flash" {
				geminiModels = append(geminiModels, name)
			}
			if channel.Type == constant.ChannelTypeAnthropic && model.MembershipClaudeModelSupported(upstream) {
				claudeModels = append(claudeModels, name)
			}
			if channel.Type == constant.ChannelTypeOpenAI && upstream == "gpt-4o-realtime-preview" {
				realtimeModels = append(realtimeModels, name)
			}
			if channel.Type == constant.ChannelTypeOpenAI && upstream == "whisper-1" {
				transcriptionModels = append(transcriptionModels, name)
			}
			if channel.Type == constant.ChannelTypeOpenAI && (upstream == "tts-1" || upstream == "tts-1-hd") {
				speechModels = append(speechModels, name)
			}
			if channel.Type == constant.ChannelTypeOpenAI && model.MembershipImageModelSupported(upstream) {
				imageModels = append(imageModels, name)
			}
			if model.MembershipVideoChannelSupported(channel.Type) && model.MembershipVideoModelSupported(upstream) {
				videoModels = append(videoModels, name)
			}
			if model.MembershipTextChannelSupported(channel.Type) && model.MembershipTextModelSupported(upstream) {
				models = append(models, name)
			}
		}
		if len(models) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: models, Profile: model.MembershipTextProfile, Unit: model.MembershipUnitTokens})
		}
		if len(geminiModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: geminiModels, Profile: model.MembershipGeminiProfile, Unit: model.MembershipUnitTokens})
		}
		if len(claudeModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: claudeModels, Profile: model.MembershipClaudeProfile, Unit: model.MembershipUnitTokens})
		}
		if len(realtimeModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: realtimeModels, Profile: model.MembershipRealtimeProfile, Unit: model.MembershipUnitTokens})
		}
		if len(transcriptionModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: transcriptionModels, Profile: model.MembershipTranscriptionProfile, Unit: model.MembershipUnitAudioMillis})
		}
		if len(speechModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: speechModels, Profile: model.MembershipSpeechProfile, Unit: model.MembershipUnitCharacters})
		}
		if len(videoModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: videoModels, Profile: model.MembershipVideoProfile, Unit: model.MembershipUnitVideos})
		}
		if len(imageModels) > 0 {
			options = append(options, option{Id: channel.Id, Name: channel.Name, Models: imageModels, Profile: model.MembershipImageProfile, Unit: model.MembershipUnitImages})
		}
	}
	common.ApiSuccess(c, options)
}

